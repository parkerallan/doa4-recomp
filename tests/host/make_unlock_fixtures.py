"""Writes tests/host/doa4_unlock_fixtures.h (usage: image.bin fresh_ups.dat full_ups.dat out.h) from the decrypted Rev 1 image and two saves."""
import sys
img_path, fresh_path, full_path, out_path = sys.argv[1:5]
img = open(img_path, 'rb').read()
B = 0x82000000
def im(a, n): return img[a - B:a - B + n]
fresh = open(fresh_path, 'rb').read()[0xB928:0xB9B4]
full = open(full_path, 'rb').read()[0xB928:0xB9B4]
assert len(fresh) == len(full) == 0x8C
roster = bytes(img[0x82C34400 + 40 * k - B] for k in range(18))
def arr(name, data, comment):
    rows = []
    for i in range(0, len(data), 16):
        rows.append('    ' + ', '.join(f'0x{b:02X}' for b in data[i:i + 16]) + ',')
    return f'// {comment}\ninline constexpr std::array<uint8_t, {len(data)}> {name} = {{{{\n' + '\n'.join(rows) + '\n}};\n'
parts = [
 '// Generated by make_unlock_fixtures.py from the decrypted DOA4 Rev 1 image (default.xex),\n'
 '// the user\'s fresh ups.dat and the community "100%" ups.dat (freestepdodge), 2026-10-28.\n'
 '// Do not edit by hand: these are the real bytes the unlock logic is checked against.\n',
 '#pragma once\n\n#include <array>\n#include <cstdint>\n\nnamespace doa4_fixtures {\n',
 arr('kProfileIndexToChar', im(0x82C5A014, 23), 'Image 0x82C5A014: profile index -> charId.'),
 arr('kMaxCostumes', im(0x82C34888, 25), 'Image 0x82C34888: maximum costume count per charId.'),
 arr('kStoryRosterChars', roster, 'Image 0x82C34400 + 40*k, byte 0: the Story roster charIds (18 entries).'),
 arr('kFreshProfile', fresh, "User's fresh ups.dat 0xB928..0xB9B3 = profile P+0x3FC0..P+0x404B."),
 arr('kFullProfile', full, '100% ups.dat 0xB928..0xB9B3 = profile P+0x3FC0..P+0x404B.'),
 '\n}  // namespace doa4_fixtures\n',
]
open(out_path, 'w', newline='\n').write('\n'.join(parts))
print('wrote', out_path)
