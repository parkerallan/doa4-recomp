"""Writes tests/host/doa4_tweak_fixtures.h (usage: patch.toml image.bin out.h): the Xenia Rev 1 patch bytes and the image's originals."""
import sys, tomllib
patch_path, img_path, out_path = sys.argv[1:4]
img = open(img_path, 'rb').read()
B = 0x82000000
doc = tomllib.load(open(patch_path, 'rb'))
want = {
    'All Stages Available in Tag Mode': 'kTagAllStages',
    'All Characters Unlocked': 'kMpHiddenCharacters',
}
out = ['// Generated by make_tweak_fixtures.py from the Xenia patch file',
       '// "544307D1 - DEAD OR ALIVE 4 (Rev1).patch.toml" (patches by ryu_highabusa) and the',
       '// decrypted Rev 1 image, 2026-10-28. Do not edit by hand.', '',
       '#pragma once', '', '#include <cstdint>', '#include <vector>', '',
       'namespace doa4_fixtures {', '',
       'struct FixturePatch {', '  uint32_t address;', '  std::vector<uint8_t> on;        // the patch file\'s bytes',
       '  std::vector<uint8_t> original;  // the image\'s bytes at the address', '};', '']
for p in doc['patch']:
    if p['name'] not in want: continue
    # tomllib groups be8 and array entries separately, so order by address
    items = []
    for e in p.get('be8', []): items.append((e['address'], bytes([e['value']])))
    for e in p.get('array', []): items.append((e['address'], bytes.fromhex(e['value'])))
    items.sort()
    out.append(f'// {p["name"]}')
    out.append(f'inline const std::vector<FixturePatch> {want[p["name"]]} = {{')
    f = lambda bs: '{' + ', '.join(f'0x{x:02X}' for x in bs) + '}'
    for a, b in items:
        orig = img[a - B:a - B + len(b)]
        out.append(f'    {{0x{a:08X}, {f(b)}, {f(orig)}}},')
    out.append('};')
    out.append('')
out.append('}  // namespace doa4_fixtures')
open(out_path, 'w', newline='\n').write('\n'.join(out) + '\n')
print('wrote', out_path)
